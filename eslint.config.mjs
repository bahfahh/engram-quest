// ESLint config for EngramQuest — uses eslint-plugin-obsidianmd (Obsidian official guidelines).
import tsparser from "@typescript-eslint/parser";
import obsidianmd from "eslint-plugin-obsidianmd";

// Extract only obsidianmd/* rules from recommended config
const recommended = obsidianmd.configs.recommended;
const jsonRecommended = recommended.find((config) =>
  Array.isArray(config.files) &&
  config.files.includes("package.json") &&
  config.language === "json/json"
);
const disabledRecommendedRules = Object.fromEntries(
  recommended.flatMap((config) => Object.keys(config.rules || {})).map((rule) => [rule, "off"])
);

export default [
  ...recommended,
  {
    files: ["src/**/*.js"],
    languageOptions: {
      parser: tsparser,
      parserOptions: {
        project: "./tsconfig.eslint.json",
        sourceType: "module",
      },
      globals: {
        require: "readonly",
        module: "writable",
        exports: "writable",
        __dirname: "readonly",
        __filename: "readonly",
        // Replaced with text by esbuild (`define` in scripts/build-options.mjs).
        __EXPLAINER_PAGE__: "readonly",
        __SETUP_PROMPT__: "readonly",
      },
    },
    rules: {
      // Disable general TS/JS rules that produce false positives on plain CJS modules
      "@typescript-eslint/no-require-imports": "off",
      "@typescript-eslint/no-unused-vars": "off",
      "@typescript-eslint/no-unused-expressions": "off",
      "@typescript-eslint/no-deprecated": "off",
      // A name that is used but never declared throws when that line runs (ticket-035).
      // tests/undeclared-identifiers.test.js runs this rule on every file in src/ during `npm test`.
      "no-undef": "error",
      "no-empty": "off",
    },
  },
  {
    // Runs inside the sandboxed Deep Dive iframe, which has its own document and window.
    // Obsidian's activeDocument would point at the wrong document there, so plain `document` is correct.
    files: ["src/explainer/page/runtime.js"],
    rules: {
      "obsidianmd/prefer-active-doc": "off",
    },
  },
  {
    // Generated by scripts/embed-skills.js: the skill files (markdown that talks about vault config
    // folders and contains regex examples) embedded as strings. None of it is plugin code that reads
    // a config path or uses a lookbehind.
    files: ["src/skills/embedded-skills.js"],
    rules: {
      "obsidianmd/hardcoded-config-path": "off",
      "obsidianmd/regex-lookbehind": "off",
    },
  },
  {
    files: ["manifest.json"],
    language: "json/json",
    plugins: jsonRecommended.plugins,
    rules: {
      ...disabledRecommendedRules,
      "no-irregular-whitespace": "off",
      "obsidianmd/validate-manifest": "error",
    },
  },
  {
    ignores: [
      "node_modules/**",
      "main.js",          // built output — minified, not source
      "tests/**",
      "scripts/**",
      "bundled-skills/**",
    ],
  },
];
