"use strict";
// Video looks (ADR-26). Built-in looks come from looks.json — the one registry to edit when a look
// is added or re-tiered. Learners with Pro can also have their own looks, which the video skill saves
// under engram-quest/video/looks/{id}/look.json. The plugin only lists and gates looks; the skill
// owns how each one is drawn. Pure of Obsidian UI — functions take a vault adapter.

const REGISTRY = require("./looks.json");

const USER_LOOKS_DIR = "engram-quest/video/looks";
// The skill reads this copy of the registry; it is rewritten whenever the bundled registry changes.
const CATALOG_PATH = "engram-quest/videos/looks.json";
const AUTO = "auto";

/** Look ids are ASCII kebab-case so they survive file names, sync services and JSON keys. */
function isLookId(id) {
  return typeof id === "string" && /^[a-z0-9][a-z0-9-]{0,63}$/.test(id);
}

const LOOKS = (REGISTRY.looks || [])
  .filter((l) => l && isLookId(l.id) && l.id !== AUTO && (l.tier === "free" || l.tier === "pro"))
  .map((l) => ({ id: l.id, tier: l.tier, name: l.name || {}, suits: l.suits || {} }));

/** Localised text of a { "zh-tw": …, en: … } map (or a plain string), falling back to English, then `fallback`. */
function localText(map, locale, fallback = "") {
  if (typeof map === "string") return map || fallback;
  return (map && (map[locale] || map.en)) || fallback;
}

/** Looks the learner saved with the skill. Folders without a valid look.json, or reusing a built-in id, are skipped. */
async function listUserLooks(adapter) {
  let listing = null;
  try { listing = await adapter.list(USER_LOOKS_DIR); } catch { return []; }
  if (!listing || !Array.isArray(listing.folders)) return [];
  const builtIn = new Set(LOOKS.map((l) => l.id));
  const found = await Promise.all(listing.folders.map(async (folder) => {
    const id = String(folder).split("/").pop();
    if (!isLookId(id) || id === AUTO || builtIn.has(id)) return null;
    let raw = null;
    try { raw = JSON.parse(await adapter.read(`${USER_LOOKS_DIR}/${id}/look.json`)); } catch { return null; }
    if (!raw || typeof raw !== "object") return null;
    return { id, tier: "mine", name: raw.name || id, suits: raw.suits || "" };
  }));
  return found.filter(Boolean).sort((a, b) => a.id.localeCompare(b.id));
}

function findLook(id, userLooks = []) {
  return LOOKS.find((l) => l.id === id) || userLooks.find((l) => l.id === id) || null;
}

/** Whether the skill may use this look for the learner: free looks always; Pro and own looks need Pro. */
function canUseLook(id, isPro, userLooks = []) {
  if (id === AUTO) return true;
  const look = findLook(id, userLooks);
  if (!look) return false;
  return look.tier === "free" || !!isPro;
}

/** Write the registry copy the skill reads, only when it differs (avoids churn in synced vaults). */
async function syncCatalog(adapter) {
  const next = JSON.stringify({
    about: "Generated by the EngramQuest plugin from its look registry — do not edit here. tier: free | pro; Pro looks may be used only when settings.json has pro: true.",
    looks: LOOKS,
  }, null, 2);
  let current = null;
  try { current = await adapter.read(CATALOG_PATH); } catch { current = null; }
  if (current === next) return false;
  await adapter.mkdir(CATALOG_PATH.slice(0, CATALOG_PATH.lastIndexOf("/"))).catch(() => {});
  await adapter.write(CATALOG_PATH, next);
  return true;
}

module.exports = { AUTO, LOOKS, USER_LOOKS_DIR, CATALOG_PATH, isLookId, localText, listUserLooks, findLook, canUseLook, syncCatalog };
